#!/usr/bin/env python3
"""Pick the key frames of a black-and-white video and pack them into badapple_frames.h for the firmware.

Usage: python3 tools/badapple.py <folder_with_pngs> [--keys 240] [--fps 3] [--preview sheet.png]

A key frame is one that changed the most since the last frame kept (greedy, by differing pixels),
so recognizable poses stay and still stretches are skipped. Played back at a few fps: cheap on purpose.
Needs Pillow (pip install pillow).
"""
import argparse
import glob
import os

from PIL import Image

W, H = 88, 64  # 11 bytes per row; the 4:3 video only gets stretched by 3 %
DEFAULT_OUT = os.path.join(os.path.dirname(__file__), "..", "cyber_hairclip", "src", "effects", "badapple_frames.h")


def load(path):
    img = Image.open(path).convert("L").resize((W, H), Image.BOX)
    return bytes(1 if p >= 128 else 0 for p in img.tobytes())


def pick(frames, keys, min_gap=3, max_gap=90):
    """Bisect the change threshold until ~keys frames are kept. max_gap avoids holes longer than 3 s."""
    def run(th):
        out, last = [0], frames[0]
        for i in range(1, len(frames)):
            gap = i - out[-1]
            if gap < min_gap:
                continue
            if gap >= max_gap or sum(a != b for a, b in zip(frames[i], last)) >= th:
                out.append(i)
                last = frames[i]
        return out

    lo, hi = 1, W * H
    while lo < hi:
        mid = (lo + hi) // 2
        if len(run(mid)) > keys:
            lo = mid + 1
        else:
            hi = mid
    return run(lo)


def pack(bits):  # row by row, MSB = leftmost pixel (Adafruit drawBitmap format)
    out = bytearray()
    for y in range(H):
        for x0 in range(0, W, 8):
            b = 0
            for x in range(x0, x0 + 8):
                b = b << 1 | bits[y * W + x]
            out.append(b)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src", help="folder with the video frames as PNG, in order")
    ap.add_argument("--keys", type=int, default=240, help="how many key frames to keep")
    ap.add_argument("--fps", type=int, default=3, help="playback rate on the hairclip")
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--preview", help="also save a contact sheet of the chosen frames")
    a = ap.parse_args()

    paths = sorted(glob.glob(os.path.join(a.src, "*.png")))
    assert paths, f"no PNG files in {a.src}"
    frames = [load(p) for p in paths]
    idx = pick(frames, a.keys)
    data = b"".join(pack(frames[i]) for i in idx)
    assert len(data) == len(idx) * W * H // 8

    with open(a.out, "w") as f:
        f.write(f"// Generated by tools/badapple.py: {len(idx)} key frames out of {len(paths)}. Do not edit.\n")
        f.write(f"const int BA_W = {W}, BA_H = {H}, BA_N = {len(idx)}, BA_FPS = {a.fps};\n")
        f.write("const uint8_t BA_FRAMES[] PROGMEM = {  // PROGMEM: without it the ESP8266 would copy this into RAM\n")
        for i in range(0, len(data), 22):
            f.write("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 22]) + ",\n")
        f.write("};\n")
    print(f"{len(idx)} key frames out of {len(paths)} -> {len(data) // 1024} KB, {len(idx) / a.fps:.0f} s at {a.fps} fps")

    if a.preview:
        cols = 16
        sheet = Image.new("L", (cols * (W + 2), (len(idx) + cols - 1) // cols * (H + 2)), 80)
        for n, i in enumerate(idx):
            im = Image.frombytes("L", (W, H), bytes(v * 255 for v in frames[i]))
            sheet.paste(im, (n % cols * (W + 2), n // cols * (H + 2)))
        sheet.save(a.preview)


if __name__ == "__main__":
    main()
